KX = math.cos(math.radians(54))
def chaikin(p, it=2):
    for _ in range(it):
        q = [p[0]]
        for a, b in zip(p, p[1:]): q += [[.75*a[0]+.25*b[0], .75*a[1]+.25*b[1]], [.25*a[0]+.75*b[0], .25*a[1]+.75*b[1]]]
        p = q + [p[-1]]
    return p
def resample(p, n):
    d = [0.0]
    for a, b in zip(p, p[1:]): d.append(d[-1] + math.hypot((b[0]-a[0])*KX, b[1]-a[1]))
    out = []
    for i in range(n):
        s = d[-1] * i / (n - 1); j = max(k for k in range(len(d)) if d[k] <= s + 1e-12); j = min(j, len(p) - 2)
        u = (s - d[j]) / ((d[j+1] - d[j]) or 1); out.append([round(p[j][0] + (p[j+1][0]-p[j][0])*u, 4), round(p[j][1] + (p[j+1][1]-p[j][1])*u, 4)])
    return out
